/**
 * Atomically creates a blend case (optionally promoting a blend_plans row)
 * via the create_blend_case RPC. Backs the "Plan Blend" action. The
 * case_number is generated by the database (next_blend_case_number()) --
 * the browser no longer supplies one. Throws if the tank already has an
 * active case or the plan is already promoted; the unique indexes are the
 * real guarantee under concurrency, this is just the friendly error path.
 */
async function createBlendCase({
  operator,
  pq,
  tank,
  planId = null,
  grade = 'REGULAR',
  tankNo = '',
  rowLabel = null,
  plannedEstVolBbl = null,
  plannedEstRvp = null,
  window: windowInfo = {},
  createdBy = null,
  deliveries = [],
}) {
  const { data, error } = await supabase.rpc('create_blend_case', {
    p_operator: operator,
    p_pq: pq,
    p_tank: tank,
    p_plan_id: planId,
    p_grade: grade,
    p_tank_no: tankNo,
    p_row_label: rowLabel,
    p_planned_est_vol_bbl: plannedEstVolBbl,
    p_planned_est_rvp: plannedEstRvp,
    p_window: windowInfo,
    p_created_by: createdBy,
    p_deliveries: deliveries,
  });
  assertNoError(error, 'createBlendCase');
  return data;
}

/** Convenience wrapper: promote a proposed blend_plans row into a case. */
async function promoteBlendPlan(plan, { operator, pq, note }) {
  return createBlendCase({
    operator,
    pq,
    tank: plan.tank,
    tankNo: plan.tank_no,
    planId: plan.id,
    grade: plan.grade,
    rowLabel: plan.label,
    plannedEstVolBbl: plan.est_tov_bbl,
    plannedEstRvp: plan.incoming_rvp,
    window: { lastTruck: plan.truck_finish, note },
    createdBy: operator,
  });
}

/** Update a blend_plans row directly (used for defer / reopen actions on
 *  a not-yet-promoted plan -- low risk, plans aren't the audited record). */
async function updateBlendPlan(planDbId, patch) {
  const { data, error } = await supabase
    .from('blend_plans')
    .update(patch)
    .eq('id', planDbId)
    .select()
    .single();
  assertNoError(error, 'updateBlendPlan');
  return data;
}

